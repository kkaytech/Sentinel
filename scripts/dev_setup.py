#!/usr/bin/env python3
"""Local development setup: database roles, the `sentinel_dev` database, migrations, demo users.

    backend/.venv/bin/python scripts/dev_setup.py [--database NAME] [--reset]

`--database sentinel_e2e --reset` gives the end-to-end tests a clean database each run; its
settings go to `.env.e2e`. The role passwords are shared with `.env.dev`, because roles belong
to the cluster, not to one database.

Connects as a PostgreSQL superuser (PGHOST, PGPORT, PGUSER; default localhost:5432 as the
current OS user). Safe to re-run. Secrets are generated once and written to `.env.dev` and
`.demo-credentials`, both git-ignored; nothing secret is printed.
"""

from __future__ import annotations

import argparse
import getpass
import os
import secrets
import subprocess
import sys
from pathlib import Path

import psycopg
from psycopg import sql

REPO = Path(__file__).resolve().parents[1]
DEV_ENV_FILE = REPO / ".env.dev"
CREDENTIALS = REPO / ".demo-credentials"
ROLES = {
    "sentinel_owner": "",
    "sentinel_app": "NOINHERIT CONNECTION LIMIT 20",
    "sentinel_reader": "NOINHERIT CONNECTION LIMIT 5",
}
DEMO_USERS = [
    ("admin", "Demo Administrator", "ADMIN"),
    ("analyst", "Demo Analyst", "ANALYST"),
    ("approver", "Demo Approver", "APPROVER"),
]


def read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    pairs = (line.split("=", 1) for line in path.read_text().splitlines() if "=" in line)
    return {k.strip(): v.strip() for k, v in pairs if not k.startswith("#")}


def main() -> int:
    host = os.environ.get("PGHOST", "localhost")
    port = os.environ.get("PGPORT", "5432")
    superuser = os.environ.get("PGUSER", getpass.getuser())
    superuser_password = os.environ.get("PGPASSWORD")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--database", default="sentinel_dev")
    parser.add_argument("--reset", action="store_true", help="drop and recreate the database")
    args = parser.parse_args()
    database = args.database
    if args.reset and database == "sentinel_dev" and not os.environ.get("SENTINEL_RESET_DEV"):
        print("Refusing to reset sentinel_dev. Set SENTINEL_RESET_DEV=1 to confirm.", file=sys.stderr)
        return 2
    is_dev = database == "sentinel_dev"
    env_file = DEV_ENV_FILE if is_dev else REPO / f".env.{database.removeprefix('sentinel_')}"
    # Role passwords come from .env.dev when it exists, so a second database never breaks dev.
    env = {**read_env(env_file), **{k: v for k, v in read_env(DEV_ENV_FILE).items()
                                    if k.startswith("DEV_SENTINEL_")}}
    passwords = {
        role: env.get(f"DEV_{role.upper()}_PASSWORD") or secrets.token_urlsafe(24) for role in ROLES
    }
    demo_password = env.get("DEV_DEMO_PASSWORD") or secrets.token_urlsafe(12)

    with psycopg.connect(host=host, port=port, user=superuser, password=superuser_password,
                         dbname="postgres", autocommit=True) as conn:
        for role, options in ROLES.items():
            exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (role,)).fetchone()
            statement = "ALTER ROLE {} PASSWORD {}" if exists else (
                "CREATE ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION "
                f"NOBYPASSRLS {options} PASSWORD {{}}"
            )
            conn.execute(sql.SQL(statement).format(sql.Identifier(role), sql.Literal(passwords[role])))
        if args.reset:
            conn.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(database)))
        if not conn.execute("SELECT 1 FROM pg_database WHERE datname = %s", (database,)).fetchone():
            conn.execute(
                sql.SQL("CREATE DATABASE {} OWNER sentinel_owner ENCODING 'UTF8' TEMPLATE template0").format(
                    sql.Identifier(database)
                )
            )

    def url(role: str) -> str:
        return f"postgresql+psycopg://{role}:{passwords[role]}@{host}:{port}/{database}"

    env_out = {
        "SENTINEL_APP_DATABASE_URL": url("sentinel_app"),
        "SENTINEL_OWNER_DATABASE_URL": url("sentinel_owner"),
        "SENTINEL_SESSION_SECRET": env.get("SENTINEL_SESSION_SECRET") or secrets.token_urlsafe(48),
        "SENTINEL_ENV": "development",
        "SENTINEL_AI_ENABLED": "false",
        **{f"DEV_{role.upper()}_PASSWORD": value for role, value in passwords.items()},
        "DEV_DEMO_PASSWORD": demo_password,
    }
    env_file.write_text("# Generated by scripts/dev_setup.py. Local development only.\n"
                        + "".join(f"{k}={v}\n" for k, v in env_out.items()))
    env_file.chmod(0o600)

    python = Path(sys.executable)
    run_env = {**os.environ, **env_out}
    subprocess.run([str(python), "-m", "alembic", "upgrade", "head"], cwd=REPO / "backend",
                   env=run_env, check=True)
    for username, display_name, role in DEMO_USERS:
        result = subprocess.run(
            [str(python), "-m", "sentinel.identity.cli", "create-user", "--username", username,
             "--display-name", display_name, "--role", role],
            cwd=REPO / "backend", env={**run_env, "SENTINEL_NEW_USER_PASSWORD": demo_password},
            capture_output=True, text=True,
        )
        if result.returncode not in (0, 1):  # 1 = the user already exists
            print(result.stderr, file=sys.stderr)
            return result.returncode
    if is_dev:
        CREDENTIALS.write_text(
            "# Local demo users (development only). All three share this password.\n"
            f"users: {', '.join(u for u, _, _ in DEMO_USERS)}\npassword: {demo_password}\n"
        )
        CREDENTIALS.chmod(0o600)
    print(f"Ready: database {database} on {host}:{port}. Settings are in {env_file.name}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
